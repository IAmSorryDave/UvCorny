#!/bin/bash

export COPILOT_PROVIDER_TYPE="${LANGUAGE_MODEL_PROVIDER_TYPE:-openai}"

if [ -n "${LANGUAGE_MODEL_PROVIDER_BASE_URL:-}" ]; then
  export COPILOT_PROVIDER_BASE_URL="$LANGUAGE_MODEL_PROVIDER_BASE_URL"
  export COPILOT_MODEL="${LANGUAGE_MODEL_PROVIDER_BASE_MODEL:?LANGUAGE_MODEL_PROVIDER_BASE_MODEL must be set when a base URL is provided}"
  if [ -n "${LANGUAGE_MODEL_PROVIDER_API_KEY:-}" ]; then
    export COPILOT_PROVIDER_API_KEY="$LANGUAGE_MODEL_PROVIDER_API_KEY"
  fi
fi
