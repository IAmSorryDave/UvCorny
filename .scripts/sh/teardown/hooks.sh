#!/bin/sh

set -eu

pre_commit_hook="$(git rev-parse --git-path hooks)/pre-commit"
if command -v pre-commit >/dev/null 2>&1 &&
   [ -f "$pre_commit_hook" ] &&
   grep -q 'generated by pre-commit' "$pre_commit_hook"; then
  pre-commit uninstall || true
fi

git update-index --no-assume-unchanged .pre-commit-config.yaml 2>/dev/null || true
